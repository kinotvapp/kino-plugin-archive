// init.mjs --bundle: the source split into src/ and bundled into plugin.js with esbuild, the layout of the Party Chat and
// Solo noticias examples (docs/plugins/README.md, "Structure a bigger plugin in files and bundle it").
import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { BUNDLE_BUILD_SCRIPT, BUNDLE_BUILT_TEST, scaffold, WITH } from "../init.mjs";
import { validate } from "../validate.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const EXAMPLE = join(HERE, "..", "..", "..", "docs", "plugins", "examples", "watch-party");

/** esbuild as the examples install it (`npm install` in docs/plugins/examples/watch-party), or null. */
function exampleEsbuild() {
  try {
    return createRequire(join(EXAMPLE, "package.json")).resolve("esbuild");
  } catch {
    return null;
  }
}

// These tests read files of the Kino repo itself (docs/plugins/, plugins/archive-org, its .gitignore). A template does
// not carry them, so they are skipped here and run in the Kino repo.
const NEEDS_KINO_REPO = "needs files of the Kino repo that this template does not have";

test("--bundle writes src/, the build script, package.json and the built check, and no hand-written plugin.js", { skip: NEEDS_KINO_REPO }, () => {
  const dir = mkdtempSync(join(tmpdir(), "kino-init-bundle-"));
  try {
    const written = scaffold(dir, { id: "mi-plugin", host: "example.org", bundle: true });
    for (const f of ["src/plugin.js", "src/site.js", "src/catalog.js", "scripts/build.mjs", "package.json", "test/built.test.mjs", "test/plugin.test.mjs", "kino-plugin.json"]) {
      assert.ok(written.includes(f), f);
    }
    assert.ok(!existsSync(join(dir, "plugin.js")), "plugin.js is generated by npm run build, never scaffolded");
    assert.ok(!existsSync(join(dir, "src", "extras.js")), "no --with, no extras");
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    assert.equal(pkg.type, "module");
    assert.equal(pkg.scripts.build, "node scripts/build.mjs");
    assert.equal(pkg.scripts["check:built"], "node scripts/build.mjs --check");
    assert.equal(pkg.devDependencies.esbuild, "^0.21.0");
    assert.match(readFileSync(join(dir, ".gitignore"), "utf8"), /^node_modules\/$/m);
    assert.equal(JSON.parse(readFileSync(join(dir, "kino-plugin.json"), "utf8")).entry, "plugin.js");
    // The same build script and built check as the examples: one recipe.
    assert.equal(readFileSync(join(dir, "scripts", "build.mjs"), "utf8"), BUNDLE_BUILD_SCRIPT);
    assert.equal(BUNDLE_BUILD_SCRIPT, readFileSync(join(EXAMPLE, "scripts", "build.mjs"), "utf8"));
    assert.equal(BUNDLE_BUILT_TEST, readFileSync(join(EXAMPLE, "test", "built.test.mjs"), "utf8"));
    assert.match(readFileSync(join(dir, "src", "plugin.js"), "utf8"), /^export \{ search, home, browse, resolve \} from "\.\/catalog\.js";$/m);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

test("--bundle --with: the extras live in src/extras.js and the entry re-exports their exports; the sources run as modules", async () => {
  const dir = mkdtempSync(join(tmpdir(), "kino-init-bundle-with-"));
  try {
    scaffold(dir, { host: "example.org", with: WITH, bundle: true });
    assert.equal(JSON.parse(readFileSync(join(dir, "kino-plugin.json"), "utf8")).apiVersion, 13);
    const entry = readFileSync(join(dir, "src", "plugin.js"), "utf8");
    assert.match(entry, /^export \{ read, image \} from "\.\/extras\.js";$/m);
    const calls = [];
    globalThis.kino = {
      fetch: async (url) => { calls.push(url); return { ok: true, status: 200, json: () => ({ results: [{ id: 7, title: "Una" }] }) }; },
      error: (code, m) => Object.assign(new Error(m), { code }),
    };
    try {
      const mod = await import(pathToFileURL(join(dir, "src", "plugin.js")).href);
      assert.deepEqual(Object.keys(mod).sort(), ["browse", "home", "image", "read", "resolve", "search"]);
      const items = await mod.search({ q: "algo" });
      assert.deepEqual(items, [{ id: "7", ref: "7", title: "Una", kind: "movie", year: undefined, poster: undefined }]);
      assert.deepEqual(calls, ["https://example.org/search?q=algo"]);
    } finally { delete globalThis.kino; }
  } finally { rmSync(dir, { recursive: true, force: true }); }
});

const esbuildPath = exampleEsbuild();
test("--bundle: src/ builds into a plugin.js the kit accepts, starting with the generated-file header", {
  skip: esbuildPath ? false : "esbuild is not installed in docs/plugins/examples/watch-party (npm install there): the build check is skipped",
}, async () => {
  const dir = mkdtempSync(join(tmpdir(), "kino-init-bundle-build-"));
  try {
    scaffold(dir, { host: "example.org", with: ["byteSource", "images"], bundle: true });
    const esbuild = await import(pathToFileURL(esbuildPath).href);
    const { buildOptions, BANNER } = await import(pathToFileURL(join(dir, "scripts", "build.mjs")).href);
    const out = (await esbuild.build(buildOptions(dir))).outputFiles[0].text;
    assert.ok(out.startsWith(BANNER + "\n"));
    assert.ok(!/^import\b/m.test(out), "one file: no import left");
    writeFileSync(join(dir, "plugin.js"), out);
    const r = await validate(dir);
    assert.deepEqual(r.problems, []);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});
